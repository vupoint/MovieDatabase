package io.viewpoint.moviedatabase.core.data.database

import android.content.Context
import androidx.room.Room
import androidx.test.ext.junit.runners.AndroidJUnit4
import androidx.test.platform.app.InstrumentationRegistry
import io.viewpoint.moviedatabase.domain.repository.entity.WantToSeeMovieEntity
import kotlinx.coroutines.runBlocking
import org.junit.Assert.assertEquals
import org.junit.Test
import org.junit.runner.RunWith

@RunWith(AndroidJUnit4::class)
class AppDatabaseTest {
    @Test
    fun preservesVersionOneDataAfterProcessorUpgrade(): Unit = runBlocking {
        val context = InstrumentationRegistry.getInstrumentation().targetContext
        val name = "room-upgrade-test.db"
        context.deleteDatabase(name)
        try {
            context.openOrCreateDatabase(name, Context.MODE_PRIVATE, null).use { database ->
                // This schema and identity hash were generated by Room 2.6.1.
                database.execSQL("CREATE TABLE IF NOT EXISTS `WantToSeeMovie` (`id` INTEGER NOT NULL, PRIMARY KEY(`id`))")
                database.execSQL("CREATE TABLE IF NOT EXISTS room_master_table (id INTEGER PRIMARY KEY,identity_hash TEXT)")
                database.execSQL("INSERT OR REPLACE INTO room_master_table (id,identity_hash) VALUES(42, '2aa514d65a2d34c8189c11e7e31c350c')")
                database.execSQL("INSERT INTO WantToSeeMovie (id) VALUES (7)")
                database.version = 1
            }

            val database = Room.databaseBuilder(context, AppDatabase::class.java, name).build()
            try {
                val dao = database.wantToSeeDao()
                assertEquals(listOf(WantToSeeMovieEntity(7)), dao.getAll())
                dao.insert(WantToSeeMovieEntity(8))
                dao.delete(WantToSeeMovieEntity(7))
            } finally {
                database.close()
            }

            val reopened = Room.databaseBuilder(context, AppDatabase::class.java, name).build()
            try {
                assertEquals(listOf(WantToSeeMovieEntity(8)), reopened.wantToSeeDao().getAll())
            } finally {
                reopened.close()
            }
        } finally {
            context.deleteDatabase(name)
        }
    }
}
